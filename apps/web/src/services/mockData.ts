export function generateMetricsSeries(metric: string, baseValue: number, length = 20): { timestamp: string; value: number }[] {
  const points: { timestamp: string; value: number }[] = [];
  const stepMs = 60000;
  const startTime = Date.now() - length * stepMs;
  for (let i = 0; i < length; i++) {
    const t = new Date(startTime + i * stepMs).toISOString();
    const noise = (Math.sin(i / 2) + Math.random() * 0.4 - 0.2) * (baseValue * 0.15);
    const spike = i > 14 && metric === 'errorRate' ? 0.07 : 0;
    points.push({ timestamp: t, value: Math.max(0, Number((baseValue + noise + spike).toFixed(4))) });
  }
  return points;
}
